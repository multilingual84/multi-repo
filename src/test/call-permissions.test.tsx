import { act, cleanup, fireEvent, render } from '@testing-library/react';
import { afterEach, expect, it, vi } from 'vitest';
import AnswerCallScreen from '@/components/AnswerCallScreen';
vi.mock('@/context/TranslationContext', () => ({ useTranslationState: () => ({ activeLanguage: 'en' }) }));
vi.mock('@/components/CallAudioControls', () => ({ default: () => null }));
vi.mock('@/lib/live-call', () => ({ LiveCall: class { start() {} hangUp() {} } }));
afterEach(() => { cleanup(); window.history.replaceState(null, '', '/'); vi.restoreAllMocks(); });
it('stops video and audio capture arriving after the screen is dismissed', async () => {
  let resolve: ((value: MediaStream) => void) | undefined;
  const audioStop = vi.fn(), videoStop = vi.fn();
  Object.defineProperty(navigator, 'mediaDevices', { configurable: true, value: { getUserMedia: () => new Promise<MediaStream>(done => { resolve = done; }) } });
  window.history.replaceState(null, '', '/#meeting-video-late');
  const view = render(<AnswerCallScreen/>);
  fireEvent.click(view.getByRole('button', { name: 'Audio call' }));
  fireEvent.click(view.getByRole('button', { name: /^Answer$/ }));
  fireEvent.click(view.getByRole('button', { name: 'Continue' }));
  fireEvent.click(view.getByRole('button', { name: 'Continue' }));
  fireEvent.click(view.getByRole('button', { name: 'Close call screen' }));
  await act(async () => { resolve?.({ getTracks: () => [{ stop: audioStop }, { stop: videoStop }] } as unknown as MediaStream); });
  expect(audioStop).toHaveBeenCalledOnce(); expect(videoStop).toHaveBeenCalledOnce();
  expect(view.queryByRole('dialog')).toBeNull();
});
it('requests neither device before both video consent steps, and cancellation captures nothing', () => {
  const getUserMedia = vi.fn();
  Object.defineProperty(navigator, 'mediaDevices', { configurable: true, value: { getUserMedia } });
  window.history.replaceState(null, '', '/#meeting-permissions');
  const view = render(<AnswerCallScreen/>);
  fireEvent.click(view.getByRole('button', { name: 'Audio call' }));
  fireEvent.click(view.getByRole('button', { name: /^Answer$/ }));
  expect(getUserMedia).not.toHaveBeenCalled();
  fireEvent.click(view.getByRole('button', { name: 'Continue' }));
  expect(getUserMedia).not.toHaveBeenCalled();
  fireEvent.click(view.getByRole('button', { name: 'Cancel' }));
  expect(getUserMedia).not.toHaveBeenCalled();
});
it('recovers denied video permission via explicitly selected audio without requesting camera', async () => {
  const getUserMedia = vi.fn().mockRejectedValueOnce(new DOMException('', 'NotAllowedError')).mockResolvedValue({ getTracks: () => [], getAudioTracks: () => [], getVideoTracks: () => [] });
  Object.defineProperty(navigator, 'mediaDevices', { configurable: true, value: { getUserMedia } });
  window.history.replaceState(null, '', '/#meeting-permissions');
  const view = render(<AnswerCallScreen/>);
  fireEvent.click(view.getByRole('button', { name: 'Audio call' }));
  fireEvent.click(view.getByRole('button', { name: /^Answer$/ }));
  fireEvent.click(view.getByRole('button', { name: 'Continue' }));
  await act(async () => { fireEvent.click(view.getByRole('button', { name: 'Continue' })); });
  expect(view.getByRole('alert')).toBeInTheDocument();
  expect(getUserMedia.mock.calls[0]?.[0].video).toEqual(expect.objectContaining({ facingMode: 'user' }));
  fireEvent.click(view.getByRole('button', { name: 'Video call' }));
  fireEvent.click(view.getByRole('button', { name: /^Answer$/ }));
  await act(async () => { fireEvent.click(view.getByRole('button', { name: 'Continue' })); });
  expect(getUserMedia.mock.calls[1]?.[0].video).toBe(false);
});